"""Human merge / split of incidents. Every moved ticket gets a correction row."""

import uuid

from sqlalchemy import func, select, update
from sqlalchemy.ext.asyncio import AsyncSession

from app.models import Correction, Incident, IncidentStatus, Ticket
from app.services.dedup import DEDUP_LOCK_KEY


class IncidentError(Exception):
    def __init__(self, status_code: int, detail: str):
        self.status_code, self.detail = status_code, detail


async def _lock(session: AsyncSession) -> None:
    # Same lock as dedup assignment, so a worker can't attach a ticket to an incident mid-merge.
    await session.execute(select(func.pg_advisory_xact_lock(DEDUP_LOCK_KEY)))


def _most_urgent(*priorities: str | None) -> str | None:
    present = [p for p in priorities if p]
    return min(present) if present else None


async def merge(session: AsyncSession, target_id: uuid.UUID, source_id: uuid.UUID, corrected_by: str) -> Incident:
    if target_id == source_id:
        raise IncidentError(422, "Cannot merge an incident into itself")
    await _lock(session)
    incidents = {
        i.id: i
        for i in await session.scalars(
            select(Incident).where(Incident.id.in_([target_id, source_id])).order_by(Incident.id).with_for_update()
        )
    }
    target, source = incidents.get(target_id), incidents.get(source_id)
    if target is None or source is None:
        raise IncidentError(404, "Incident not found")
    if source.status == IncidentStatus.MERGED or target.status == IncidentStatus.MERGED:
        raise IncidentError(409, "Incident already merged")

    moved = (
        await session.scalars(
            update(Ticket).where(Ticket.incident_id == source_id).values(incident_id=target_id).returning(Ticket.id)
        )
    ).all()
    session.add_all(
        Correction(ticket_id=t, field="incident", old_value=str(source_id), new_value=str(target_id),
                   corrected_by=corrected_by)
        for t in moved
    )
    target.ticket_count += len(moved)
    target.priority = _most_urgent(target.priority, source.priority)
    target.category = target.category or source.category
    target.team = target.team or source.team
    source.ticket_count = 0
    source.status = IncidentStatus.MERGED
    source.merged_into = target_id
    await session.commit()
    # updated_at is generated by the database; load it before the response is serialized.
    await session.refresh(target)
    return target


async def split(
    session: AsyncSession, incident_id: uuid.UUID, ticket_ids: list[uuid.UUID], corrected_by: str, title: str | None
) -> Incident:
    await _lock(session)
    incident = await session.get(Incident, incident_id, with_for_update=True)
    if incident is None:
        raise IncidentError(404, "Incident not found")
    tickets = (await session.scalars(select(Ticket).where(Ticket.id.in_(ticket_ids)))).all()
    if len(tickets) != len(set(ticket_ids)) or any(t.incident_id != incident_id for t in tickets):
        raise IncidentError(422, "All tickets must exist and belong to this incident")
    if len(tickets) >= incident.ticket_count:
        raise IncidentError(422, "Split must leave at least one ticket in the original incident")

    first = min(tickets, key=lambda t: t.created_at)
    new = Incident(
        title=title or first.subject[:200],
        category=first.category,
        team=first.team,
        priority=_most_urgent(*(t.priority for t in tickets)),
        ticket_count=len(tickets),
    )
    session.add(new)
    await session.flush()
    for t in tickets:
        t.incident_id = new.id
        session.add(Correction(ticket_id=t.id, field="incident", old_value=str(incident_id), new_value=str(new.id),
                               corrected_by=corrected_by))
    incident.ticket_count -= len(tickets)
    await session.commit()
    await session.refresh(new)
    return new
